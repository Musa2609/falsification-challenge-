"""Compact, reproducible summary of recorded results.

Reads results/summary.json and results/reference_metrics.json and writes
results/analysis_summary.md. It performs NO new measurements — it only
aggregates what the experiment recorded, so the numbers quoted in
proposal.md / README.md can be regenerated with:

    python -m src.analyze_results
"""
from __future__ import annotations

import json
from pathlib import Path

from .generate_data import bayes_single_accuracy

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"


def fmt(v):
    return "n/a" if v is None else f"{v:.4f}"


def ms(block):
    return f"{block['mean']:.3f} ± {(block['std'] if block['std'] is not None else float('nan')):.3f}"


def main():
    summary = json.loads((RESULTS / "summary.json").read_text())
    ref = json.loads((RESULTS / "reference_metrics.json").read_text())

    lines = []
    lines.append("# Recorded results — generated summary\n")
    lines.append("Generated by `python -m src.analyze_results`. Aggregates the "
                 "per-seed JSON files in `results/runs/`. Unless noted, "
                 "`P` = conflict preference index (mean ± SD over 5 seeds), "
                 "`acc` = test accuracy.\n")

    lines.append("| condition | k | (alpha,beta) | label | acc | P | drop_simple | drop_complex |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for cond, s in sorted(summary.items(), key=lambda kv: kv[0]):
        st = s["settings"]
        lines.append(
            f"| {cond} | {st['k']} | ({st['alpha']}, {st['beta']}) | {st['label_mode']}"
            f"{' shuffle' if st['shuffle_labels'] else ''}"
            f"{' swap' if st.get('swap_columns') else ''}"
            f" | {ms(s['test_accuracy'])} | {ms(s['preference_index'])}"
            f" | {ms(s['ablation_drop_simple'])} | {ms(s['ablation_drop_complex'])} |"
        )

    lines.append("\n## Analytic (oracle) Bayes accuracies\n")
    lines.append("| (alpha,beta) | A_simple | A_complex |")
    lines.append("|---|---|---|")
    for key in sorted(ref):
        e = ref[key]
        lines.append(f"| {key} | {e['bayes_single_simple']:.4f} | {e['bayes_single_complex']:.4f} |")

    lines.append("\n## Key derived contrasts\n")
    b = summary["baseline"]
    lines.append(f"- Baseline (k=8, matched): P = {ms(b['preference_index'])}, "
                 f"acc = {ms(b['test_accuracy'])} (Bayes 0.7386).")
    for cond in ["k1_null", "k2", "k4", "k32", "k32_more_data",
                 "baseline_swapped", "shuffled_labels"]:
        if cond in summary:
            s = summary[cond]
            lines.append(f"- {cond}: P = {ms(s['preference_index'])}, "
                         f"acc = {ms(s['test_accuracy'])}.")
    for cond in ["single_simple", "single_complex_k2", "single_complex_k4",
                 "single_complex", "single_complex_k32", "single_complex_longrun_5x"]:
        if cond in summary:
            s = summary[cond]
            lines.append(f"- {cond}: isolated test acc = {ms(s['test_accuracy'])} "
                         f"(Bayes 0.8413 where the label depends only on that feature).")
    for cond in ["strength_simple_favored", "strength_complex_favored",
                 "strength_simple_favored_k2", "strength_complex_favored_k2"]:
        if cond in summary:
            s = summary[cond]
            lines.append(f"- {cond}: P = {ms(s['preference_index'])}, "
                         f"acc = {ms(s['test_accuracy'])}.")

    out = RESULTS / "analysis_summary.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nWritten to {out}")


if __name__ == "__main__":
    main()
